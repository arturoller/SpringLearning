-- Lekcja Test06Testcontainers: tabela klientów — TEN SAM skrypt działa na H2 i na PostgreSQL.
-- Adres e-mail jest UNIKALNY (ale może być pusty: kilka wartości NULL nie łamie UNIQUE w H2 ani w PostgreSQL).
CREATE TABLE customer (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(100) NOT NULL,
    city  VARCHAR(50)  NOT NULL,
    email VARCHAR(100) UNIQUE,
    vip   BOOLEAN      NOT NULL DEFAULT FALSE
);
