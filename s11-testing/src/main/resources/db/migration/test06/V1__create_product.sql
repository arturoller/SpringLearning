-- Schemat lekcji Test06Testcontainers. SQL zgodny z H2 i PostgreSQL (IDENTITY, NUMERIC, VARCHAR, UNIQUE) —
-- te same migracje wykonują się na H2 w testach wycinków i na PostgreSQL w kontenerze.
CREATE TABLE product (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(100)   NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    CONSTRAINT uk_product_name UNIQUE (name)
);
