-- Schemat lekcji Tx05ProgrammaticTransactions: zamówienia klientów (customer_order) i dziennik audytu (audit_log).
-- Kwota zamówienia musi być dodatnia (CHECK), numer zamówienia — unikalny: oba ograniczenia służą w testach
-- do wywołania błędu w środku transakcji.
CREATE TABLE customer_order (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(20)    NOT NULL,
    amount       NUMERIC(12, 2) NOT NULL,
    status       VARCHAR(20)    NOT NULL,
    CONSTRAINT uk_customer_order_number UNIQUE (order_number),
    CONSTRAINT ck_customer_order_amount CHECK (amount > 0)
);

CREATE TABLE audit_log (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message VARCHAR(200) NOT NULL
);
