-- Lekcja Tx05ProgrammaticTransactions: cennik sklepu, dziennik zmian cen i zamówienia z płatnością.
-- CHECK (price > 0) — baza sama pilnuje, żeby cena była dodatnia (zła cena = błąd przy zapisie, czyli przy commicie).
create table products (
    sku   varchar(20)   not null primary key,
    name  varchar(100)  not null,
    price numeric(10, 2) not null check (price > 0)
);

