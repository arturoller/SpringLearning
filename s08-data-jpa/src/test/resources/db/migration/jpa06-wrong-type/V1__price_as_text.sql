-- Encja Product ma BigDecimal price → ddl-auto=validate musi zatrzymać start aplikacji.
create sequence products_seq start with 1001 increment by 50;

create table products (
    id       bigint       not null primary key,
    sku      varchar(20)  not null unique,
    name     varchar(100) not null,
    category varchar(20)  not null,
    price    varchar(20)  not null,
    stock    integer      not null default 0
);

-- Tabela klientów zgodna z V1 lekcji — żeby po ćwiczeniu 2 (encja Customer) jedynym błędem nadal była cena.
create table customers (
    id        bigint       generated by default as identity primary key,
    full_name varchar(100) not null,
    city      varchar(50),
    email     varchar(255) unique,
    vip       boolean      not null default false
);
