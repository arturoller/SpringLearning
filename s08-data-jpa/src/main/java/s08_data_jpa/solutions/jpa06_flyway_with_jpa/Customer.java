package s08_data_jpa.solutions.jpa06_flyway_with_jpa;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * Rozwiązanie ćwiczenia 2 lekcji Jpa06FlywayWithJpa: encja dopasowana do ISTNIEJĄCEJ tabeli customers
 * (migracja V1__create_tables.sql). Zajrzyj dopiero po własnej próbie!
 */
@Entity
@Table(name = "customers")
public class Customer {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)   // kolumna "generated by default as identity" z migracji
    private Long id;

    @Column(name = "full_name", nullable = false, length = 100)   // pole name ↔ kolumna full_name
    private String name;

    @Column(length = 50)
    private String city;

    @Column(unique = true)
    private String email;

    private boolean vip;

    protected Customer() {
    }

    public Customer(String name, String city, String email, boolean vip) {
        this.name = name;
        this.city = city;
        this.email = email;
        this.vip = vip;
    }

    public Long getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getCity() {
        return city;
    }

    public String getEmail() {
        return email;
    }

    public boolean isVip() {
        return vip;
    }
}
