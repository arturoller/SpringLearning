/**
 * <pre>
 * TEMAT: Encje JPA — obiekt Javy ↔ wiersz tabeli
 *        (JPA, Jakarta Persistence API = standardowe API utrwalania obiektów; ORM, object-relational mapping =
 *         mapowanie obiektowo-relacyjne; entity = encja; Hibernate = najpopularniejsza implementacja JPA;
 *         persistence context = kontekst utrwalania; dirty checking = automatyczne wykrywanie zmian)
 *
 * W SKRÓCIE:
 *   W dziale s07_data_jdbc pisałeś SQL ręcznie i ręcznie przepisywałeś kolumny do pól obiektu. ORM robi to za Ciebie:
 *   opisujesz klasę adnotacjami (@Entity, @Id, @Column), a Hibernate sam generuje INSERT, SELECT, UPDATE i DELETE.
 *   Klasa z @Entity to ENCJA — jej obiekt odpowiada jednemu wierszowi tabeli. Hibernate pilnuje encji w tzw. kontekście
 *   utrwalania: jeśli w transakcji zmienisz pole encji pobranej z bazy, Hibernate SAM wyśle UPDATE — bez save().
 *
 * ANALOGIA: tłumacz przysięgły między dwoma krajami.
 *   Java mówi językiem obiektów (pola, referencje), baza — językiem tabel (kolumny, klucze). Hibernate to tłumacz:
 *   dostaje „słownik” (adnotacje na encji) i tłumaczy w obie strony. Dodatkowo prowadzi notes (kontekst utrwalania):
 *   zapisuje, jak obiekt wyglądał, gdy go przyniósł z bazy, a na koniec transakcji porównuje i zgłasza bazie zmiany.
 *
 * JAK TO DZIAŁA:
 *   start aplikacji (Spring Boot + spring-boot-starter-data-jpa):
 *     1. autokonfiguracja tworzy DataSource (źródło połączeń z bazą, pula HikariCP)
 *     2. HibernateJpaAutoConfiguration tworzy EntityManagerFactory (fabrykę menedżerów encji)
 *     3. skanowanie: klasy z @Entity w pakiecie klasy @SpringBootApplication i jego podpakietach
 *     4. ddl-auto (dla bazy wbudowanej bez Flyway: create-drop) → Hibernate wysyła CREATE TABLE dla każdej encji
 *   w transakcji:
 *     persist(obiekt)   → obiekt staje się ZARZĄDZANY (managed), INSERT teraz albo przy flush (zależy od @Id)
 *     find(Klasa, id)   → SELECT, Hibernate tworzy obiekt konstruktorem bez argumentów i wypełnia pola
 *     zmiana pola       → nic się nie dzieje… aż do flush (przed commitem): porównanie ze „zdjęciem” → UPDATE
 *
 * SŁÓWKA:
 *   entity = encja; table = tabela; column = kolumna; id/primary key = klucz główny; generated value = wartość
 *   generowana; identity = tożsamość (tu: autonumeracja w kolumnie); sequence = sekwencja (licznik w bazie);
 *   nullable = dopuszczający NULL; unique = unikalny; length = długość; enumerated = wyliczeniowy; ordinal = numer
 *   porządkowy; persist = utrwal; managed = zarządzany; detached = odłączony; flush = wypchnij (zmiany do bazy);
 *   clear = wyczyść; dirty = brudny (zmieniony); ddl (data definition language) = język definicji danych (CREATE TABLE).
 *
 * ZOBACZ TEŻ: s07_data_jdbc/Jdbc01JdbcClient (to samo „ręcznie” w SQL), t29_jdbc_databases/Jdbc05Dao (DAO w czystej
 *             Javie), t06_oop_basics/Oop05ObjectMethods (equals i hashCode), t08_enums/Enums01Basics (enum i ordinal),
 *             s08_data_jpa/Jpa02Repositories (repozytoria — dalej już bez EntityManagera).
 * </pre>
 */
