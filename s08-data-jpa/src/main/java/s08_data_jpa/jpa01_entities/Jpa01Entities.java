    // =================================================================================================
    //
    //   spring.jpa.hibernate.ddl-auto:
    //     none         — Hibernate nie dotyka schematu
    //     validate     — tylko SPRAWDZA, czy tabele pasują do encji (lekcja Jpa06FlywayWithJpa)
    //     update       — próbuje dopisać brakujące tabele/kolumny (nigdy nie usuwa)
    //     create       — usuwa i tworzy tabele przy starcie
    //     create-drop  — jak create + usuwa przy zamknięciu aplikacji
    //   Domyślnie (Spring Boot 4.1, HibernateDefaultDdlAutoProvider): baza WBUDOWANA (H2) i nikt inny nie zarządza
    //   schematem → create-drop; baza zewnętrzna albo Flyway włączony → none. Test sekcji 7 to sprawdza.
    //
    //   spring.jpa.show-sql=true — Hibernate wypisuje każde zapytanie na konsolę (profil jpa01 i @DataJpaTest
