    //   W produkcji schemat robią migracje (Flyway, lekcja Jpa06), a Hibernate ma validate albo none.
    //
    // DOBRA PRAKTYKA: show-sql tylko do nauki. Dlaczego? Pisze na System.out z pominięciem systemu logów. W prawdziwej
    //   aplikacji: logging.level.org.hibernate.SQL=debug (logger SQL) i ewentualnie
    //   logging.level.org.hibernate.orm.jdbc.bind=trace (wartości parametrów).

    // =================================================================================================
    // 8. KONTEKST UTRWALANIA i DIRTY CHECKING — UPDATE bez save()
    // =================================================================================================
    //
    // Kontekst utrwalania (persistence context) = „notes” EntityManagera na czas transakcji:
    //   • mapa id → obiekt: dwa find tego samego id w jednej transakcji zwracają TEN SAM obiekt (bez drugiego SELECT),
    //   • dla każdej encji „zdjęcie” (snapshot) wartości z chwili odczytu.
    // Stany encji: NEW (nowa, Hibernate jej nie zna) → persist → MANAGED (zarządzana) → clear/koniec transakcji →
    //   DETACHED (odłączona) → merge → znowu MANAGED (jako kopia!); remove → REMOVED (do usunięcia).
    //
    //   Product managed = em.find(Product.class, id);   // MANAGED + zdjęcie
    //   managed.setPrice(new BigDecimal("12.50"));      // tylko zmiana pola w Javie
    //   em.flush();                                     // porównanie ze zdjęciem → UPDATE products set ... where id=?
    //
    // Flush dzieje się sam: przed commitem transakcji i przed zapytaniem, którego wynik mógłby zależeć od zmian.
    // W testach wołamy go ręcznie, a potem clear(), żeby kolejny odczyt naprawdę szedł do bazy, a nie do „notesu”.
    // Hibernate domyślnie aktualizuje WSZYSTKIE kolumny (update products set name=?, price=?, sku=?, status=? ...).
    //
    // PUŁAPKA: encja odłączona (po clear albo pobrana w innej, zakończonej transakcji) — zmiana jej pól NIE trafia do
    //   bazy (test sekcji 8). Dlaczego? Nie ma jej w żadnym notesie, więc nikt jej nie porównuje. Trzeba ją dołączyć:
    //   em.merge(...) (albo repository.save(...) — lekcja Jpa02Repositories).
    //
    // DOBRA PRAKTYKA: zmiany encji rób wewnątrz transakcji (@Transactional w serwisie), a nie „na zapas” wołaj save po
    //   każdej zmianie. Dlaczego? Dirty checking i tak wyśle UPDATE, a zbędne save na zarządzanej encji to szum w kodzie.

