    // =================================================================================================
    // 2. KLUCZ GŁÓWNY: @GeneratedValue — IDENTITY kontra SEQUENCE (Product kontra Category)
    // =================================================================================================
    //
    //   IDENTITY  — numer nadaje BAZA w chwili INSERT (kolumna "generated by default as identity").
    //               Hibernate MUSI wykonać INSERT już przy persist, żeby poznać id. Nie da się grupować INSERT-ów.
    //   SEQUENCE  — numer z sekwencji w bazie (Category: "create sequence categories_seq start with 1 increment by 50").
    //               Hibernate pobiera numer przy persist, a INSERT odkłada do flush. „increment by 50” = Hibernate bierze
    //               od razu pulę 50 numerów (optymalizator pooled) — mniej zapytań o sekwencję.
    //   AUTO      — (domyślne, gdy napiszesz samo @GeneratedValue) Hibernate 7 dla Long wybiera SEQUENCE.
    //
    // Test sekcji 2: po persist Product (IDENTITY) wiersz JEST w tabeli; po persist Category (SEQUENCE) id już jest,
    // a wiersza jeszcze NIE MA — pojawia się dopiero po flush.
    //
    // PUŁAPKA: nie zakładaj, że id zaczynają się od 1 i rosną o 1. Dlaczego? Sekwencja rezerwuje pule po 50, a wycofana
    //   transakcja (rollback) nie oddaje numerów. W testach nigdy nie sprawdzaj „id == 1”.
    //
    // DOBRA PRAKTYKA: na bazach z sekwencjami (PostgreSQL, Oracle, H2) wybieraj SEQUENCE. Dlaczego? Pozwala Hibernate
    //   grupować INSERT-y (batching — wysyłanie paczkami) i odkładać je do flush; IDENTITY wymusza INSERT natychmiast.
    //   IDENTITY jest prostsze i typowe dla MySQL — też działa poprawnie, tylko wolniej przy masowym zapisie.

    // =================================================================================================
    // 3. @Column — nullable, length, unique (i precision/scale dla pieniędzy)
    // =================================================================================================
    //
    //   @Column(nullable = false, length = 100)  → name varchar(100) not null
    //   @Column(nullable = false, unique = true, length = 20)  → sku varchar(20) not null unique
    //   @Column(nullable = false, precision = 10, scale = 2)   → price numeric(10,2) not null
    //   bez @Column: String → varchar(255), dopuszcza NULL
    //
    // Te ustawienia działają w DWÓCH miejscach:
    //   • przy generowaniu tabeli (ddl-auto) — stają się ograniczeniami w bazie (NOT NULL, UNIQUE),
    //   • nullable = false sprawdza też sam Hibernate przed zapisem: persist z name == null → PropertyValueException
    //     („not-null property references a null or transient value”) — test sekcji 3.
    //   Duplikat SKU wykrywa dopiero BAZA: Hibernate dostaje błąd i rzuca ConstraintViolationException (naruszenie
    //   ograniczenia). Przez repozytorium Springa ten sam błąd przyjdzie jako DataIntegrityViolationException.
    //
    // PUŁAPKA: @Column(length = 20) NIE sprawdza długości w Javie. Dlaczego? To tylko informacja do CREATE TABLE.
    //   Gdy schemat robi Flyway (lekcja Jpa06), liczy się to, co napisałeś w migracji. Walidację danych wejściowych
    //   robi Bean Validation (@NotBlank, @Size — dział o walidacji), nie @Column.

    // =================================================================================================
    // 4. ENUM: @Enumerated(EnumType.STRING), a nie ORDINAL (Product kontra LegacyProduct)
    // =================================================================================================
    //
    //   @Enumerated(EnumType.STRING)   → w kolumnie "HIDDEN"  (na H2 Hibernate 7 tworzy nawet typ enum('ACTIVE',...))
    //   @Enumerated(EnumType.ORDINAL)  → w kolumnie 1         (numer pozycji: ACTIVE=0, HIDDEN=1, DISCONTINUED=2)
    //   bez @Enumerated                → ORDINAL! (domyślne w JPA)
    //
    // PUŁAPKA: ORDINAL (i brak @Enumerated) zapisuje NUMER pozycji stałej. Dlaczego to groźne? Ktoś dopisze nową stałą
    //   NA POCZĄTKU enuma (np. DRAFT) — wszystkie numery się przesuną i stare wiersze nagle znaczą co innego (1 było
    //   HIDDEN, a teraz jest ACTIVE). Żaden błąd, żaden wyjątek — po prostu złe dane. PYTANIE REKRUTACYJNE.
    //
    // DOBRA PRAKTYKA: zawsze @Enumerated(EnumType.STRING). Dlaczego? Nazwa stałej nie zależy od kolejności, a w bazie
    //   od razu widać, co znaczy wartość. Uwaga tylko na ZMIANĘ NAZWY stałej — to wymaga migracji danych.

    // =================================================================================================
    // 5. KONSTRUKTOR BEZ ARGUMENTÓW i dlaczego encja NIE jest rekordem (RecordProduct)
    // =================================================================================================
    //
    // Przy odczycie Hibernate: 1) tworzy pusty obiekt konstruktorem bez argumentów, 2) wpisuje wartości do pól.
    // Dlatego encja MUSI mieć taki konstruktor. Może być protected — Hibernate go użyje, a Twój kod nie stworzy
    // „pustego” produktu przez przypadek (publiczny konstruktor z argumentami pilnuje poprawności).
    //
    // Encja to NIE rekord (record). Dlaczego?
    //   • rekord nie ma konstruktora bez argumentów → test sekcji 5: zapis RecordProduct działa, ale odczyt kończy się
    //     org.hibernate.InstantiationException: No default constructor for entity ...
    //   • pola rekordu są final (niezmienne), a encja ŻYJE: zmieniasz cenę, Hibernate wykrywa zmianę (sekcja 8),
    //   • rekord jest klasą final — Hibernate nie może zrobić jego podklasy-pośrednika (proxy) do leniwego ładowania,
    //   • equals/hashCode rekordu porównuje WSZYSTKIE pola — dla encji to złe (sekcja 6).
    //   Rekordy są za to idealne na DTO i projekcje (lekcja Jpa04CustomQueries) oraz jako @Embeddable (Hibernate 6.2+).
    //
    // DOBRA PRAKTYKA: protected konstruktor bez argumentów + publiczny konstruktor z polami wymaganymi + settery tylko
    //   dla pól, które naprawdę wolno zmieniać. Dlaczego? Encja jest zmienna (mutable), ale nie musi być „otwarta na
    //   wszystko” — np. Product nie ma setId ani setSku.

    // =================================================================================================
    // 6. equals/hashCode ENCJI — pułapka generowanego id (NaiveCustomer kontra Customer)
    // =================================================================================================
    //
    // NaiveCustomer: equals i hashCode liczone z id (Objects.hashCode(id)).
    //   Set<NaiveCustomer> set = new HashSet<>();
    //   set.add(naive);          // id == null → hashCode = 0 → obiekt w „szufladce” 0
    //   em.persist(naive);       // baza nadała id → hashCode = np. 7
    //   set.contains(naive)      // false! HashSet szuka w szufladce 7, a obiekt leży w szufladce 0
    // Co gorsza, dwa NOWE obiekty (oba id == null) są według tego equals RÓWNE — HashSet zatrzyma tylko jeden.
    // Oba efekty sprawdza test sekcji 6. PYTANIE REKRUTACYJNE: „jak napisać equals/hashCode dla encji JPA?”
    //
    // Customer (poprawnie):
    //   equals:   ten sam obiekt → true; inaczej równe tylko gdy id != null i id są równe
    //   hashCode: getClass().hashCode() — STAŁY, więc nie zmienia się po zapisie
    // Stały hashCode jest zgodny z kontraktem (równe obiekty mają równy hashCode), a że wszystkie produkty trafiają do
    // jednej szufladki? Zbiory encji w pamięci są małe, poprawność jest ważniejsza.
    //
    // PUŁAPKA: Lombok @Data albo @EqualsAndHashCode na encji (t20_lombok/Lombok03DataValueBuilder) — porównuje wszystkie
    //   pola, w tym id i kolekcje. Dlaczego źle? hashCode zmienia się po zapisie i po każdej zmianie pola, a dotknięcie
    //   leniwej kolekcji w hashCode potrafi wywołać dodatkowe zapytania do bazy.
    //
    // DOBRA PRAKTYKA: albo NIE nadpisuj equals/hashCode (zostaje tożsamość obiektu — w jednym kontekście utrwalania
    //   Hibernate i tak daje jeden obiekt na wiersz), albo wzór z Customer. Dlaczego? Oba nie psują zbiorów po zapisie.

