-- Lekcja Sec03UsersPasswords: użytkownicy sklepu.
-- username UNIQUE: ostatnia linia obrony przed dwoma kontami o tej samej nazwie (także przy wyścigu dwóch rejestracji).
-- password_hash: NIGDY samo hasło — tylko wynik PasswordEncoder z prefiksem algorytmu, np. {bcrypt}$2a$10$...
-- roles: role bez prefiksu ROLE_, oddzielone przecinkami (prosto, na potrzeby lekcji; w dużym systemie osobna tabela).
CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    roles         VARCHAR(200) NOT NULL,
    enabled       BOOLEAN      NOT NULL,
    CONSTRAINT uk_app_users_username UNIQUE (username)
);
