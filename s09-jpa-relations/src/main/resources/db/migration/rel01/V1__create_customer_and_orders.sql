-- Schemat lekcji Rel01ManyToOne: klient (customer) i jego zamówienia (orders — NIE "order": to słowo zastrzeżone w SQL).
CREATE TABLE customer (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    CONSTRAINT uk_customer_email UNIQUE (email)
);

-- Klucz obcy (foreign key) customer_id: każde zamówienie MUSI wskazywać istniejącego klienta.
-- To właśnie ta kolumna jest relacją @ManyToOne — w tabeli orders, po stronie "wiele".
CREATE TABLE orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(20) NOT NULL,
    ordered_on   DATE        NOT NULL,
    customer_id  BIGINT      NOT NULL,
    CONSTRAINT uk_orders_order_number UNIQUE (order_number),
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customer (id)
);

-- Indeks na kluczu obcym: H2 i MySQL tworzą go same, PostgreSQL NIE — a bez niego każde "zamówienia klienta X"
-- czyta całą tabelę. Piszemy go jawnie, żeby migracja działała tak samo na każdej bazie.
CREATE INDEX ix_orders_customer_id ON orders (customer_id);
