-- Lekcja Rel01ManyToOne: kategoria (strona "jeden") i produkty (strona "wiele").
-- Klucz obcy category_id jest w tabeli products — to tabela produktow "wskazuje" swoja kategorie.

create table categories (
    id   bigint generated by default as identity primary key,
    name varchar(50) not null unique
);

create table products (
    id          bigint generated by default as identity primary key,
    name        varchar(100) not null,
    price       numeric(10, 2) not null,
    category_id bigint not null,
    constraint fk_products_category foreign key (category_id) references categories (id)
);

-- Indeks na kluczu obcym: zapytania "produkty z kategorii X" i zlaczenia (join) nie przegladaja calej tabeli.
create index ix_products_category on products (category_id);

-- Produkty "w starym stylu": relacja z domyslnym fetch (EAGER) i kategoria opcjonalna (category_id moze byc NULL).
create table eager_products (
    id          bigint generated by default as identity primary key,
    name        varchar(100) not null,
    category_id bigint,
    constraint fk_eager_products_category foreign key (category_id) references categories (id)
);
