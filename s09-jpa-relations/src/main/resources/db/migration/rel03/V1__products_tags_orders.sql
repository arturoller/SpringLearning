-- Lekcja Rel03ManyToMany: produkty <-> tagi (wiele do wielu) przez tabele laczaca product_tags.

create table products (
    id    bigint generated by default as identity primary key,
    name  varchar(100) not null,
    price numeric(10, 2) not null
);

create table tags (
    id   bigint generated by default as identity primary key,
    name varchar(50) not null unique
);

-- Tabela laczaca (join table): sama para kluczy obcych; para jest kluczem glownym, wiec nie ma duplikatow.
create table product_tags (
    product_id bigint not null,
    tag_id     bigint not null,
    primary key (product_id, tag_id),
    constraint fk_product_tags_product foreign key (product_id) references products (id),
    constraint fk_product_tags_tag foreign key (tag_id) references tags (id)
);

-- PRZED: ta sama relacja jako List (bag) — do pomiaru, ile instrukcji SQL kosztuje usuniecie jednego tagu.
create table list_products (
    id   bigint generated by default as identity primary key,
    name varchar(100) not null
);

create table list_product_tags (
    list_product_id bigint not null,
    tag_id          bigint not null,
    constraint fk_list_product_tags_product foreign key (list_product_id) references list_products (id),
    constraint fk_list_product_tags_tag foreign key (tag_id) references tags (id)
);

-- PUŁAPKA: @ManyToMany z CascadeType.REMOVE.
create table dangerous_products (
    id   bigint generated by default as identity primary key,
    name varchar(100) not null
);

create table dangerous_product_tags (
    dangerous_product_id bigint not null,
    tag_id               bigint not null,
    primary key (dangerous_product_id, tag_id),
    constraint fk_dangerous_product_tags_product foreign key (dangerous_product_id) references dangerous_products (id),
    constraint fk_dangerous_product_tags_tag foreign key (tag_id) references tags (id)
);

-- Relacja z dodatkowa kolumna (quantity) — juz nie @ManyToMany, tylko osobna encja OrderLine.
create table orders (
    id            bigint generated by default as identity primary key,
    customer_name varchar(100) not null
);

create table order_lines (
    id         bigint generated by default as identity primary key,
    order_id   bigint not null,
    product_id bigint not null,
    quantity   integer not null,
    constraint fk_order_lines_order foreign key (order_id) references orders (id),
    constraint fk_order_lines_product foreign key (product_id) references products (id)
);
