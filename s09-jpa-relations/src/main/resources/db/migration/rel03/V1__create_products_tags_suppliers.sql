-- Schemat lekcji Rel03ManyToMany: produkt N—N tag (tabela łącząca product_tag) oraz produkt N—N dostawca
-- z DANYMI powiązania (cena zakupu) — encja pośrednia product_supplier.
CREATE TABLE product (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(100)   NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    CONSTRAINT uk_product_name UNIQUE (name)
);

CREATE TABLE tag (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    CONSTRAINT uk_tag_name UNIQUE (name)
);

-- Tabela łącząca (join table): jeden wiersz = "produkt X ma tag Y". Klucz główny z obu kolumn — ta sama para
-- nie może wystąpić dwa razy. Dwa klucze obce, każdy do swojej tabeli.
CREATE TABLE product_tag (
    product_id BIGINT NOT NULL,
    tag_id     BIGINT NOT NULL,
    CONSTRAINT pk_product_tag PRIMARY KEY (product_id, tag_id),
    CONSTRAINT fk_product_tag_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT fk_product_tag_tag FOREIGN KEY (tag_id) REFERENCES tag (id)
);
-- Indeks po drugiej kolumnie: klucz główny (product_id, tag_id) przyspiesza szukanie po product_id,
-- a "produkty z tagiem X" szukają po tag_id.
CREATE INDEX ix_product_tag_tag_id ON product_tag (tag_id);

CREATE TABLE supplier (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

-- Encja pośrednia: własne id + UNIQUE na parze (product_id, supplier_id) + dane powiązania (purchase_price).
CREATE TABLE product_supplier (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT         NOT NULL,
    supplier_id    BIGINT         NOT NULL,
    purchase_price NUMERIC(10, 2) NOT NULL,
    CONSTRAINT uk_product_supplier UNIQUE (product_id, supplier_id),
    CONSTRAINT fk_product_supplier_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT fk_product_supplier_supplier FOREIGN KEY (supplier_id) REFERENCES supplier (id)
);
CREATE INDEX ix_product_supplier_supplier_id ON product_supplier (supplier_id);
