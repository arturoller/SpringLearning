-- Schemat lekcji Rel06EntityToDto: klient 1—N zamówienie (orders) 1—N pozycja (order_line) N—1 produkt.
-- customer.password_hash — pole, które NIGDY nie może wyjść poza aplikację (sekcja 1: ujawnianie pól).
CREATE TABLE customer (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(100) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    CONSTRAINT uk_customer_email UNIQUE (email)
);

CREATE TABLE product (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(100)   NOT NULL,
    price NUMERIC(10, 2) NOT NULL
);

CREATE TABLE orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(20)  NOT NULL,
    customer_id  BIGINT       NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    note         VARCHAR(200),
    CONSTRAINT uk_orders_order_number UNIQUE (order_number),
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customer (id)
);
CREATE INDEX ix_orders_customer_id ON orders (customer_id);

CREATE TABLE order_line (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL,
    product_id BIGINT         NOT NULL,
    quantity   INTEGER        NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_order_line_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_line_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT ck_order_line_quantity CHECK (quantity > 0)
);
CREATE INDEX ix_order_line_order_id ON order_line (order_id);
