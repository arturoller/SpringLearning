-- Lekcja Rel06EntityToDto: produkty (bez relacji) oraz klienci <-> zamowienia (relacja dwukierunkowa).
-- Kolumny purchase_price i internal_note to dane WEWNETRZNE sklepu - nie powinny trafic do odpowiedzi API.

create table products (
    id             bigint generated by default as identity primary key,
    sku            varchar(20)    not null unique,
    name           varchar(100)   not null,
    price          numeric(10, 2) not null,
    purchase_price numeric(10, 2) not null
);

create table customers (
    id            bigint generated by default as identity primary key,
    name          varchar(100) not null,
    city          varchar(50)  not null,
    email         varchar(100),
    internal_note varchar(200)
);

create table orders (
    id          bigint generated by default as identity primary key,
    number      varchar(20) not null unique,
    status      varchar(20) not null,
    customer_id bigint      not null,
    constraint fk_orders_customer foreign key (customer_id) references customers (id)
);

create index ix_orders_customer on orders (customer_id);
