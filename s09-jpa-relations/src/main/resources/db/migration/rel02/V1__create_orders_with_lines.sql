-- Schemat lekcji Rel02OneToMany: zamówienie (orders) 1—N pozycja (order_line) N—1 produkt (product).
-- Klienta pomijamy — relację zamówienie → klient omawia Rel01ManyToOne.
CREATE TABLE product (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(100)   NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    CONSTRAINT uk_product_name UNIQUE (name)
);

CREATE TABLE orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(20) NOT NULL,
    CONSTRAINT uk_orders_order_number UNIQUE (order_number)
);

-- Klucz obcy order_id jest w tabeli POZYCJI (strona "wiele") — dlatego to OrderLine jest stroną właściciela.
-- unit_price = cena jednostkowa z chwili zakupu (cena produktu może się później zmienić).
CREATE TABLE order_line (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL,
    product_id BIGINT         NOT NULL,
    quantity   INTEGER        NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_order_line_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_line_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT ck_order_line_quantity CHECK (quantity > 0)
);
CREATE INDEX ix_order_line_order_id ON order_line (order_id);
CREATE INDEX ix_order_line_product_id ON order_line (product_id);

-- Sekcja 2 lekcji: JEDNOKIERUNKOWE @OneToMany z @JoinColumn (Invoice → InvoiceLine, bez pola invoice w pozycji).
-- invoice_id MUSI dopuszczać NULL: Hibernate najpierw wstawia pozycję bez klucza obcego, a potem go UPDATE-uje.
CREATE TABLE invoice (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number VARCHAR(20) NOT NULL
);

CREATE TABLE invoice_line (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT,
    description VARCHAR(100)   NOT NULL,
    amount      NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_invoice_line_invoice FOREIGN KEY (invoice_id) REFERENCES invoice (id)
);
