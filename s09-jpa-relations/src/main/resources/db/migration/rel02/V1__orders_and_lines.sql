-- Lekcja Rel02OneToMany: zamowienie (strona "jeden") i jego pozycje (strona "wiele", wlasciciel klucza obcego).

create table orders (
    id            bigint generated by default as identity primary key,
    customer_name varchar(100) not null
);

create table order_lines (
    id           bigint generated by default as identity primary key,
    product_name varchar(100) not null,
    quantity     integer not null,
    order_id     bigint not null,
    constraint fk_order_lines_order foreign key (order_id) references orders (id)
);

create index ix_order_lines_order on order_lines (order_id);

-- Wersja "naiwna" (PRZED): klucz obcy moze byc NULL, zeby bylo widac, co sie dzieje, gdy nikt go nie ustawi.
create table naive_orders (
    id            bigint generated by default as identity primary key,
    customer_name varchar(100) not null
);

create table naive_order_lines (
    id           bigint generated by default as identity primary key,
    product_name varchar(100) not null,
    quantity     integer not null,
    order_id     bigint,
    constraint fk_naive_order_lines_order foreign key (order_id) references naive_orders (id)
);
