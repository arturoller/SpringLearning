-- Projekt Cap02Reservations: stanowiska serwisowe sklepu i ich rezerwacje.

create table desks (
    id   bigint generated by default as identity primary key,
    code varchar(20)  not null,
    name varchar(100) not null,
    constraint uk_desks_code unique (code)
);

-- Rezerwacje: cala historia (takze anulowane). Przedzial [starts_at, ends_at) - koniec NIE nalezy do rezerwacji,
-- wiec 10:00-12:00 i 12:00-13:00 sie nie nakladaja.
create table reservations (
    id               bigint generated by default as identity primary key,
    desk_id          bigint       not null,
    customer_email   varchar(100) not null,
    starts_at        timestamp    not null,
    ends_at          timestamp    not null,
    status           varchar(20)  not null,
    created_at       timestamp    not null,
    cancelled_at     timestamp,
    -- pod CWICZENIE 2 (przypomnienia): kiedy wyslano przypomnienie (null = jeszcze nie)
    reminder_sent_at timestamp,
    constraint fk_reservations_desk foreign key (desk_id) references desks (id),
    constraint ck_reservations_range check (ends_at > starts_at)
);

create index ix_reservations_desk_time on reservations (desk_id, starts_at);
create index ix_reservations_email on reservations (customer_email);

-- ZAJETOSC: jeden wiersz = jedna godzina jednego stanowiska zajeta przez AKTYWNA rezerwacje.
-- Klucz glowny (desk_id, slot_start) to ograniczenie w bazie, ktorego nie oszuka zaden wyscig: dwie transakcje nie
-- zapisza tej samej godziny tego samego stanowiska. Anulowanie usuwa wiersze - godzina znow jest wolna.
-- (Nakladania sie PRZEDZIALOW nie da sie zapisac jako UNIQUE; PostgreSQL ma do tego EXCLUDE USING gist, H2 - nie.)
create table occupied_slots (
    reservation_id bigint    not null,
    desk_id        bigint    not null,
    slot_start     timestamp not null,
    constraint pk_occupied_slots primary key (desk_id, slot_start),
    constraint fk_occupied_slots_reservation foreign key (reservation_id) references reservations (id),
    constraint fk_occupied_slots_desk foreign key (desk_id) references desks (id)
);

create index ix_occupied_slots_reservation on occupied_slots (reservation_id);

-- Powiadomienia "wyslane" do klientow (tu: zapisane w tabeli - zamiast prawdziwego emaila).
create table notifications (
    id             bigint generated by default as identity primary key,
    reservation_id bigint       not null,
    recipient      varchar(100) not null,
    message        varchar(300) not null,
    created_at     timestamp    not null
);
