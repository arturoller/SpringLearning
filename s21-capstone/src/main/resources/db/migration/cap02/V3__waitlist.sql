-- Wersja 3 schematu: lista oczekujacych - przygotowana pod CWICZENIE 3 projektu Cap02Reservations.
-- Jeden wpis = klient czeka na JEDNA godzine (slot_start) jednego stanowiska. Kolejnosc = id (kto pierwszy, ten lepszy).

create table waitlist_entries (
    id             bigint generated by default as identity primary key,
    desk_id        bigint       not null,
    slot_start     timestamp    not null,
    customer_email varchar(100) not null,
    created_at     timestamp    not null,
    constraint fk_waitlist_desk foreign key (desk_id) references desks (id),
    -- ten sam klient nie zapisze sie dwa razy na te sama godzine
    constraint uk_waitlist_entry unique (desk_id, slot_start, customer_email)
);
