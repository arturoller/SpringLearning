-- Projekt Cap01ShopApi: schemat sklepu. Kazda regula, ktorej MOZE pilnowac baza, jest tu zapisana jako ograniczenie
-- (constraint): unikalny sku, dodatnia cena, stan >= 0, ilosc > 0, klucze obce. Serwis sprawdza to samo wczesniej
-- i zwraca czytelny blad - baza jest ostatnia linia obrony (gdy ktos ominie serwis albo dwa zapytania przyjda naraz).

create table products (
    id       bigint generated by default as identity primary key,
    sku      varchar(20)    not null,
    name     varchar(100)   not null,
    category varchar(20)    not null,
    price    numeric(10, 2) not null,
    stock    integer        not null,
    constraint uk_products_sku unique (sku),
    constraint ck_products_price check (price > 0),
    constraint ck_products_stock check (stock >= 0)
);

create table customers (
    id    bigint generated by default as identity primary key,
    name  varchar(100) not null,
    city  varchar(50)  not null,
    email varchar(100),
    vip   boolean      not null,
    -- unique pozwala na wiele wartosci NULL: klienci bez emaila nie blokuja sie nawzajem
    constraint uk_customers_email unique (email)
);

create table orders (
    id          bigint generated by default as identity primary key,
    customer_id bigint         not null,
    status      varchar(20)    not null,
    total       numeric(12, 2) not null,
    created_at  timestamp      not null,
    constraint fk_orders_customer foreign key (customer_id) references customers (id)
);

create table order_lines (
    id         bigint generated by default as identity primary key,
    order_id   bigint         not null,
    product_id bigint         not null,
    quantity   integer        not null,
    -- cena z chwili zamowienia (kopia): pozniejsza zmiana ceny produktu NIE zmienia starych zamowien
    unit_price numeric(10, 2) not null,
    constraint fk_order_lines_order foreign key (order_id) references orders (id),
    constraint fk_order_lines_product foreign key (product_id) references products (id),
    constraint ck_order_lines_quantity check (quantity > 0)
);

-- Indeksy pod zapytania API: lista zamowien po statusie, pozycje zamowienia, zamowienia klienta.
create index ix_orders_status on orders (status);
create index ix_orders_customer on orders (customer_id);
create index ix_order_lines_order on order_lines (order_id);
create index ix_order_lines_product on order_lines (product_id);
