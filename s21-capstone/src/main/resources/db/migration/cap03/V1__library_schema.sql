-- Projekt Cap03LibraryWithAuth: uzytkownicy (bibliotekarze i czytelnicy), ksiazki (jeden wiersz = jeden egzemplarz)
-- i wypozyczenia.

create table library_users (
    id            bigint generated by default as identity primary key,
    username      varchar(50)  not null,
    -- haslo NIGDY jawnym tekstem: skrot BCrypt z prefiksem {bcrypt} (DelegatingPasswordEncoder)
    password_hash varchar(100) not null,
    full_name     varchar(100) not null,
    role          varchar(20)  not null,
    constraint uk_library_users_username unique (username),
    constraint ck_library_users_role check (role in ('BIBLIOTEKARZ', 'CZYTELNIK'))
);

create table books (
    id          bigint generated by default as identity primary key,
    call_number varchar(20)  not null,
    title       varchar(200) not null,
    author      varchar(100) not null,
    -- czy egzemplarz jest wypozyczony; zmiana TEGO wiersza + version chroni przed dwoma wypozyczeniami naraz
    on_loan     boolean      not null,
    version     bigint       not null,
    constraint uk_books_call_number unique (call_number)
);

create table loans (
    id          bigint generated by default as identity primary key,
    book_id     bigint        not null,
    reader_id   bigint        not null,
    loaned_on   date          not null,
    due_on      date          not null,
    returned_on date,
    fine        numeric(8, 2),
    -- pod CWICZENIE 1 (przedluzenie): czy termin juz raz przedluzono
    extended    boolean       not null,
    constraint fk_loans_book foreign key (book_id) references books (id),
    constraint fk_loans_reader foreign key (reader_id) references library_users (id),
    constraint ck_loans_dates check (due_on >= loaned_on)
);

create index ix_loans_reader on loans (reader_id);
create index ix_loans_book on loans (book_id);
