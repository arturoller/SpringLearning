-- Rezerwacja czeka, az egzemplarz wroci; przy wypozyczeniu dostaje go tylko rezerwujacy. Status: AKTYWNA, ZREALIZOWANA.

create table book_reservations (
    id         bigint generated by default as identity primary key,
    book_id    bigint      not null,
    reader_id  bigint      not null,
    created_on date        not null,
    status     varchar(20) not null,
    constraint fk_book_reservations_book foreign key (book_id) references books (id),
    constraint fk_book_reservations_reader foreign key (reader_id) references library_users (id)
);
