-- Tabela produktów lekcji Jdbc05Repository. Ograniczenia (constraints) pilnuje baza, nie Java:
--   UNIQUE na sku    → drugi produkt o tym samym SKU jest odrzucany (DuplicateKeyException),
--   CHECK na cenie   → cena nie może być ujemna,
--   NOT NULL         → pola wymagane.
CREATE TABLE product (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku      VARCHAR(20)    NOT NULL,
    name     VARCHAR(100)   NOT NULL,
    category VARCHAR(30)    NOT NULL,
    price    DECIMAL(10, 2) NOT NULL,
    stock    INT            NOT NULL,
    CONSTRAINT uq_product_sku UNIQUE (sku),
    CONSTRAINT ck_product_price CHECK (price >= 0)
);
