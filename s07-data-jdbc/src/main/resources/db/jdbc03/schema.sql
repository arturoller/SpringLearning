CREATE TABLE employee (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100)   NOT NULL,
    department VARCHAR(30)    NOT NULL,
    salary     DECIMAL(10, 2) NOT NULL
);
