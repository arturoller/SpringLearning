    /** Hasła posortowane alfabetycznie po nazwie angielskiej (niezmienna lista). */
    private static final List<Term> SORTED = ALL.stream().sorted(BY_ENGLISH).toList();

    private SpringGlossary() {
    }

    private static Term t(String english, String polish, String definition, String lesson) {
        return new Term(english, polish, definition, lesson);
    }

    /** Wszystkie hasła, posortowane po nazwie angielskiej. */
    public static List<Term> all() {
        return SORTED;
    }

    /** Dokładne wyszukiwanie po nazwie angielskiej (bez względu na wielkość liter). */
    public static Optional<Term> findByEnglish(String english) {
        return SORTED.stream().filter(term -> term.english().equalsIgnoreCase(english)).findFirst();
    }

    /**
     * Wyszukiwanie po fragmencie nazwy angielskiej LUB polskiej (bez względu na wielkość liter; {@code Locale.ROOT} =
     * reguły niezależne od języka systemu). Wynik zachowuje kolejność słowniczka.
     */
    public static List<Term> search(String fragment) {
        String needle = fragment.toLowerCase(Locale.ROOT);
        return SORTED.stream()
                .filter(term -> term.english().toLowerCase(Locale.ROOT).contains(needle)
                        || term.polish().toLowerCase(Locale.ROOT).contains(needle))
                .toList();
    }
